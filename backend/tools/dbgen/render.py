"""The text of a generated rows module: one dataclass and one column tuple per table."""

from __future__ import annotations

from collections.abc import Sequence

from .rules import Column, Table, class_name

# The checked converter in app/db/values.py for each Python type.
_CONVERTERS = {"str": "text", "int": "integer", "float": "real", "bool": "flag", "bytes": "blob"}


def _annotation(column: Column) -> str:
    return f"{column.python} | None" if column.nullable else column.python


def _converter(column: Column) -> str:
    name = _CONVERTERS[column.python]
    return f"{name}_or_none" if column.nullable else name


def _table(table: Table) -> list[str]:
    name = class_name(table.name)
    lines = [
        "",
        "",
        "@dataclass(frozen=True, slots=True, kw_only=True)",
        f"class {name}:",
        f'    """A row of ``{table.name}``."""',
        "",
    ]
    lines += [f"    {column.name}: {_annotation(column)}" for column in table.columns]
    lines += [
        "",
        "    @classmethod",
        "    def from_mapping(cls, row: values.ColumnValues) -> Self:",
        "        return cls(",
    ]
    lines += [
        f'            {column.name}=values.{_converter(column)}(row, "{column.name}"),'
        for column in table.columns
    ]
    lines += [
        "        )",
        "",
        "",
        f"{table.name.upper()}_COLUMNS: Final = (",
    ]
    lines += [f'    "{column.name}",' for column in table.columns]
    lines.append(")")
    return lines


def render(chain: str, tables: Sequence[Table]) -> str:
    lines = [
        f'"""Rows of the {chain} database, generated by ``python -m tools.dbgen``.',
        "",
        "Do not edit: the Alembic migrations are the source. Change a migration and run the tool;",
        "every column is typed from its declared type, and ``None`` only where it is nullable.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from typing import Final, Self",
        "",
        "from .. import values",
    ]
    for table in tables:
        lines += _table(table)
    return "\n".join(lines) + "\n"
